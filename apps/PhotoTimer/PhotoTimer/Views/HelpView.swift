import SwiftUI

/// 「使い方・仕組み」の説明画面。CEO要望(2026-09-05)により追加。
/// アプリ開発が初めてのCEO・将来のユーザーにも伝わるよう、専門用語には説明を添えている。
/// ホーム画面右上の「?」からいつでも見返せるようにしている(初回だけでなく後からでも確認できるように)。
struct HelpView: View {
    @Environment(\.dismiss) private var dismiss

    var body: some View {
        NavigationStack {
            Form {
                Section("待ち時間について") {
                    Text("絞り込み条件は、写真が選ばれた瞬間にその場で判定しています。あらかじめすべての写真を調べておくわけではないので、次の1枚が見つかるまで少し待つことがあります。")
                    Text("該当する写真が少ない条件(あまり撮っていない色・カテゴリなど)ほど、待ち時間は長くなりやすい傾向があります。")
                    Text("条件にぴったり合う写真が少ない時も、近い写真から順番に表示するようにしているので、何も表示されないことはありません。")
                }

                Section("雰囲気(色)・カテゴリの判定について") {
                    Text("色やカテゴリの判定は、AI(端末に内蔵された画像認識のしくみ)による自動判定です。100%正確というわけではなく、「鮮やか」を選んだのに落ち着いた色の写真が混ざったり、「犬」を選んだつもりが違うものが出てくることもあります。")
                    Text("これはこのアプリの個性のようなものです。意外な写真との出会いも、ひとつの楽しみ方として気軽に受け止めてもらえたら嬉しいです。")
                    Text("「犬」「猫」「人」だけは専用の高精度な判定を使っていますが、それ以外のカテゴリ(食べ物・海・花など)は一般的な判定を使うため、精度はやや低めです。")
                    Text("色は「写真全体を平均した色」で判定しています。写真の一部分にしか写っていない色は、判定に反映されにくいことがあります。")
                }

                Section("場所で絞り込むには") {
                    Text("撮った場所で絞り込むには、写真そのものに位置情報が記録されている必要があります。")
                    Text("iPhoneの設定アプリで「プライバシーとセキュリティ」→「位置情報サービス」→「カメラ」がオフになっていると、新しく撮る写真に位置情報が記録されません。")
                    Text("今からオンにすれば、これから撮る写真には位置情報が付くようになりますが、すでに撮った過去の写真にあとから位置情報を付けることはできません。")
                }

                Section("プライバシーについて") {
                    Text("写真の判定処理はすべてこの端末(iPhone)の中だけで行われます。写真そのものも判定結果も、外部(インターネット)へ送信されることは一切ありません。")
                }
            }
            .navigationTitle("使い方・仕組み")
            .toolbar {
                ToolbarItem(placement: .confirmationAction) {
                    Button("閉じる") { dismiss() }
                }
            }
        }
    }
}
